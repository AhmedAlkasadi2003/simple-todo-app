/**
 * Task Data Model & Type Definitions
 *
 * NOTE FOR BACKEND LEARNERS:
 * This model defines how the frontend expects tasks to be structured when
 * communicating over HTTP. In the backend, a database entity (e.g., in PostgreSQL
 * or SQLite) might use slightly different column types or internal fields, but
 * the API serialization layer will transform it to match this contract.
 */

export type TaskStatus = "pending" | "completed";

export interface Task {
  id: string;
  title: string;
  description: string | null;
  status: TaskStatus;
  createdAt: string; // ISO 8601 format (e.g. "2026-10-26T12:00:00.000Z")
  updatedAt: string; // ISO 8601 format
}

/**
 * Data required to create a new task.
 * Note: id, status, createdAt, and updatedAt are generated by the server.
 */
export interface CreateTaskInput {
  title: string;
  description?: string;
}

/**
 * Fields that can be updated on an existing task.
 * All fields are optional (partial update / PATCH semantics).
 */
export interface UpdateTaskInput {
  title?: string;
  description?: string | null;
  status?: TaskStatus;
}

/**
 * Filter options for displaying tasks in the UI
 */
export type TaskFilterStatus = "all" | "pending" | "completed";

/**
 * Sorting criteria for task ordering
 */
export type TaskSortOption =
  | "createdAt-desc"
  | "createdAt-asc"
  | "title-asc"
  | "title-desc";

/**
 * Query parameters supported when fetching tasks
 */
export interface TaskQueryParams {
  search?: string;
  status?: TaskStatus;
  sortBy?: "createdAt" | "title";
  order?: "asc" | "desc";
}

/**
 * Summary metrics displayed at the top of the dashboard
 */
export interface TaskSummaryStats {
  total: number;
  completed: number;
  pending: number;
}

/**
 * Standard Envelope for successful single-resource API responses
 */
export interface ApiResponse<T> {
  data: T;
}

/**
 * Standard Envelope for API error responses
 */
export interface ApiErrorResponse {
  error: {
    code: string;
    message: string;
    details?: Record<string, string[]>;
  };
}
